<#
.SYNOPSIS
    代码注释盘点与中文覆盖率报告（原子需求 CMT-01）。
.DESCRIPTION
    按语言区分 XML 文档注释、行注释、块注释、XAML 注释与 PowerShell 注释，
    统计基线待译量与已译比例；支持导出 CSV、CI 校验（-Check），
    以及用 git diff --numstat 检查改动是否保持了「行数不变」（-ShapeCheck，对应 CMT-02 的硬约束）。
.PARAMETER Path
    仓库根目录，默认为脚本所在位置的上级三级。
.PARAMETER Threshold
    CI 模式下要求的单文件最低中文覆盖率百分比，默认 100。
.PARAMETER Check
    覆盖率校验模式。
.PARAMETER ShapeCheck
    校验工作区改动是否符合「不增删行」：对每个改动文件要求 git diff --numstat 的增删行数相等。
.PARAMETER BaseRef
    ShapeCheck 对比的基线引用，默认 HEAD。
.PARAMETER Csv
    可选，导出明细为 CSV 的路径。
.EXAMPLE
    .\CommentInventory.ps1
.EXAMPLE
    .\CommentInventory.ps1 -ShapeCheck
#>
param(
    [string]$Path = (Resolve-Path (Join-Path $PSScriptRoot '..\..\..')).Path,
    [int]$Threshold = 100,
    [switch]$Check,
    [switch]$ShapeCheck,
    [string]$BaseRef = 'HEAD',
    [string]$Csv
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

# 参与统计的源码扩展名
$sourceExtensions = @('.cs', '.xaml', '.cpp', '.h', '.idl', '.ps1')
# 排除构建产物与第三方目录
$excludeDirPattern = '\\(node_modules|obj|bin|\.git|x64|ARM64|Debug|Release|packages)\\'

# 这些注释是给工具的指令或机器可读内容，永远不参与翻译与覆盖率统计
$skipLinePatterns = @(
    '^#pragma',                 # C# 编译器指令
    '^//\s*<auto-generated',    # 自动生成标记
    '^//\s*<.+/>',              # 形如 <summary/> 的空标签
    '^//\s*ReSharper',          # ReSharper 指令
    '^//\s*NOLINT',             # clang-tidy 指令
    '^//\s*clang-format',       # clang-format 指令
    '^#requires',               # PowerShell 版本要求（不区分大小写，下面统一比较）
    '^//\s*https?://'           # 裸 URL 注释
)

<#
.SYNOPSIS
    判断一行注释是否应当被跳过（指令类、自动生成类、URL 类）。
#>
function Test-SkipLine {
    param([string]$Text)
    foreach ($pattern in $skipLinePatterns) {
        if ($Text -match $pattern) { return $true }
    }
    return $false
}

<#
.SYNOPSIS
    统计单个源码文件的注释行数与中文覆盖率。
.DESCRIPTION
    返回值包含六类注释的计数：XmlDoc（///）、Line（//）、Block（/* */）、Xaml（<!-- -->）、Hash（#）与合计。
#>
function Measure-SourceFile {
    param([System.IO.FileInfo]$File, [string]$Root)

    $lines = [System.IO.File]::ReadAllLines($File.FullName)
    $xmlDoc = 0; $line = 0; $block = 0; $xaml = 0; $hash = 0
    $translatable = 0; $translated = 0
    $inBlock = $false
    $inXaml = $false

    foreach ($raw in $lines) {
        $trimmed = $raw.Trim()

        # 处理跨行的块注释与 XAML 注释
        if ($inBlock) {
            $block++
            if ($translatable -ge 0 -and $trimmed -notmatch '^\*+\s*/$') { $translatable++; if ($trimmed -match '[\u4e00-\u9fff]') { $translated++ } }
            if ($trimmed -match '\*/\s*$') { $inBlock = $false }
            continue
        }
        if ($inXaml) {
            $xaml++
            $translatable++
            if ($trimmed -match '[\u4e00-\u9fff]') { $translated++ }
            if ($trimmed -match '-->\s*$') { $inXaml = $false }
            continue
        }

        if ($trimmed -match '^///') {
            $xmlDoc++
            if (Test-SkipLine -Text $trimmed) { continue }
            $translatable++
            if ($trimmed -match '[\u4e00-\u9fff]') { $translated++ }
        }
        elseif ($trimmed -match '^//' -and $trimmed -notmatch '^//\s*https?://') {
            $line++
            if (Test-SkipLine -Text $trimmed) { continue }
            $translatable++
            if ($trimmed -match '[\u4e00-\u9fff]') { $translated++ }
        }
        elseif ($trimmed -match '^/\*') {
            $inBlock = $true
            $block++
            if ($trimmed -match '^\s*/\*+' -and $trimmed -notmatch '\*/\s*$') {
                $translatable++
                if ($trimmed -match '[\u4e00-\u9fff]') { $translated++ }
            }
            if ($trimmed -match '\*/\s*$') { $inBlock = $false }
        }
        elseif ($trimmed -match '^<!--') {
            $xaml++
            if ($trimmed -notmatch '-->\s*$') { $inXaml = $true }
            $translatable++
            if ($trimmed -match '[\u4e00-\u9fff]') { $translated++ }
        }
        elseif ($trimmed -match '^#') {
            $hash++
            if (Test-SkipLine -Text $trimmed) { continue }
            $translatable++
            if ($trimmed -match '[\u4e00-\u9fff]') { $translated++ }
        }
    }

    $percent = if ($translatable -gt 0) { [math]::Round(100.0 * $translated / $translatable, 1) } else { 100.0 }

    [pscustomobject]@{
        File         = $File.FullName.Substring($Root.Length).TrimStart('\')
        XmlDoc       = $xmlDoc
        Line         = $line
        Block        = $block
        Xaml         = $xaml
        Hash         = $hash
        Comments     = $xmlDoc + $line + $block + $xaml + $hash
        Translatable = $translatable
        Translated   = $translated
        Percent      = $percent
    }
}

$root = (Resolve-Path -LiteralPath $Path).Path.TrimEnd('\') + '\'
$files = Get-ChildItem -LiteralPath $root -Recurse -File |
    Where-Object { $sourceExtensions -contains $_.Extension -and $_.FullName -notmatch $excludeDirPattern }

$results = foreach ($file in $files) { Measure-SourceFile -File $file -Root $root }

# ===== 基线汇总输出 =====
$summary = @{
    Files       = $files.Count
    Comments    = ($results | Measure-Object -Property Comments -Sum).Sum
    XmlDoc      = ($results | Measure-Object -Property XmlDoc -Sum).Sum
    Line        = ($results | Measure-Object -Property Line -Sum).Sum
    Block       = ($results | Measure-Object -Property Block -Sum).Sum
    Xaml        = ($results | Measure-Object -Property Xaml -Sum).Sum
    Hash        = ($results | Measure-Object -Property Hash -Sum).Sum
    Translatable = ($results | Measure-Object -Property Translatable -Sum).Sum
    Translated  = ($results | Measure-Object -Property Translated -Sum).Sum
}
$overall = if ($summary.Translatable -gt 0) { [math]::Round(100.0 * $summary.Translated / $summary.Translatable, 1) } else { 0 }

Write-Host ''
Write-Host ('代码文件数: {0}' -f $summary.Files)
Write-Host ('注释总量: {0} 行  （XML {1} / 行 {2} / 块 {3} / XAML {4} / PS {5}）' -f $summary.Comments, $summary.XmlDoc, $summary.Line, $summary.Block, $summary.Xaml, $summary.Hash)
Write-Host ('待译注释: {0} 行 / 已译: {1} 行 / 覆盖率: {2}%' -f $summary.Translatable, $summary.Translated, $overall)
Write-Host ''

if ($Csv) {
    $results | Export-Csv -LiteralPath $Csv -NoTypeInformation -Encoding UTF8
    Write-Host ('明细已导出: {0}' -f $Csv)
}

# ===== CI 覆盖率校验 =====
if ($Check) {
    $failures = @($results | Where-Object { $_.Comments -gt 0 -and $_.Percent -lt $Threshold })
    if ($failures.Count -gt 0) {
        Write-Host ('以下 {0} 个文件的注释中文覆盖率低于 {1}%：' -f $failures.Count, $Threshold) -ForegroundColor Yellow
        $failures | Sort-Object -Property Percent | Select-Object -First 20 | ForEach-Object {
            Write-Host ('  {0}  {1}%' -f $_.File, $_.Percent)
        }
        exit 1
    }
    Write-Host '所有含注释文件的中文覆盖率已达到要求。' -ForegroundColor Green
}

# ===== 结构形状校验（CMT-02 硬约束：不增删行） =====
if ($ShapeCheck) {
    Push-Location -LiteralPath $root
    try {
        $numstat = & git diff --numstat $BaseRef
        $violations = @()
        foreach ($entry in $numstat) {
            $parts = $entry -split "`t"
            if ($parts.Count -lt 3) { continue }
            $added = [int]$parts[0]
            $deleted = [int]$parts[1]
            $name = $parts[2]
            # 二进制文件的增删行数为空，跳过
            if ($parts[0] -eq '-') { continue }
            if ($sourceExtensions -contains ([System.IO.Path]::GetExtension($name))) {
                if ($added -ne $deleted) {
                    $violations += ('  {0}  新增 {1} / 删除 {2}' -f $name, $added, $deleted)
                }
            }
        }
        if ($violations.Count -gt 0) {
            Write-Host ('以下文件的改动破坏了「不增删行」约束：') -ForegroundColor Yellow
            $violations | ForEach-Object { Write-Host $_ }
            exit 1
        }
        Write-Host '所有改动文件的新增行数与删除行数均相等，满足「不增删行」约束。' -ForegroundColor Green
    }
    finally {
        Pop-Location
    }
}

exit 0
